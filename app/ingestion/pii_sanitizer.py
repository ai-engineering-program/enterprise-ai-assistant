from __future__ import annotations

import re
from dataclasses import dataclass


__all__ = ["PIIMatch", "PIISanitizer"]


@dataclass
class PIIMatch:
    """Одно найденное вхождение персональных данных в тексте."""

    pii_type: str  # "email" | "phone" | "snils" | "passport" | "inn"
    value: str
    start: int
    end: int


class PIISanitizer:
    """
    Regex-детектор и санитайзер СТРУКТУРИРОВАННЫХ персональных данных
    (email, телефон, СНИЛС, серия и номер паспорта, ИНН) перед
    индексированием — см. урок 4.4.

    Встраивается в конвейер поглощения СТРОГО после TextNormalizer
    (уроки 4.1-4.2) и DocumentDeduplicator (урок 4.3), и ДО chunking
    (app/rag/chunker.py):
    - После нормализации — потому что regex-паттерны ниже рассчитаны на
      предсказуемый вид текста; невыверенные кавычки, BOM и другие
      артефакты кодировки могут помешать паттерну совпасть с реальным
      написанием (тот же аргумент, что и для точного совпадения в
      дедупликации).
    - После дедупликации — чтобы не тратить работу санитайзера на
      документ, который дедупликация всё равно отбросит как дубль.
    - До chunking — чтобы персональные данные не успели разойтись по
      нескольким чанкам до того, как будут найдены и замаскированы.

    Обнаруживает только СТРУКТУРИРОВАННЫЕ персональные данные — те, что
    подчиняются жёсткому формату. ФИО, свободные упоминания адресов и
    другие неструктурированные персональные данные regex в принципе не
    может надёжно найти — для них в production нужен отдельный слой на
    основе NER-модели (см. текст урока 4.4, "NER для имён и адресов").
    Этот класс не пытается решить эту задачу: detect() спроектирован
    так, чтобы список PIIMatch от NER-слоя можно было объединить с
    результатом regex-слоя без изменения контракта sanitize().

    ВАЖНО: sanitize() возвращает не только очищенный текст, но и полный
    список найденных PIIMatch до модификации текста — это аудиторский
    след ("что было найдено, какого типа, и что с ним сделано"), без
    которого невозможно ответить на вопрос юридического отдела "мы
    точно нашли все телефоны в этом источнике?" (см. историю урока 4.4).
    """

    EMAIL_PATTERN = re.compile(
        r"[A-Za-z0-9][A-Za-z0-9._%+-]*@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"
    )
    """Уже реализовано как образец. Локальная часть, @, домен с точкой
    и доменной зоной из двух и более букв — упрощённое, но достаточное
    для реальных корпоративных адресов подмножество RFC 5322."""

    PHONE_PATTERN: re.Pattern[str] = None  # type: ignore[assignment]
    """
    TODO: скомпилировать regex для российских номеров телефона,
    покрывающий одним выражением сразу три распространённых формата:
      1. +7XXXXXXXXXX  (код страны +7, без разделителей, 10 цифр номера)
      2. 8XXXXXXXXXX   (код страны 8, без разделителей, 10 цифр номера)
      3. +7 (XXX) XXX-XX-XX  или  8 (XXX) XXX-XX-XX
         (с разделителями: пробел, круглые скобки, дефис)

    Подсказка: опишите общую форму — код страны (\\+7|8), опциональные
    скобки вокруг кода оператора, три группы цифр (3-3-2-2) с
    ОПЦИОНАЛЬНЫМИ разделителями между ними ([\\s\\-]?), а не пишите три
    отдельных альтернативы через |. Один паттерн с опциональными
    разделителями покрывает все три формата сразу, потому что
    "опциональный" разделитель совпадает и с его отсутствием.
    """

    SNILS_PATTERN: re.Pattern[str] = None  # type: ignore[assignment]
    """
    TODO: скомпилировать regex для СНИЛС — формат XXX-XXX-XXX XX
    (11 цифр, сгруппированных как 3-3-3 через дефис, затем пробел и
    последние 2 цифры), например "123-456-789 00". Разрешено покрывать
    только этот форматированный вариант с разделителями — вариант без
    разделителей (11 цифр подряд) обсуждается в тексте урока как
    осознанное ограничение первой итерации.
    """

    PASSPORT_PATTERN: re.Pattern[str] = None  # type: ignore[assignment]
    """
    TODO: скомпилировать regex для серии и номера паспорта РФ — формат
    "XX XX XXXXXX": 4 цифры серии (по 2 цифры через пробел или слитно),
    затем обязательный пробел, затем 6 цифр номера. Примеры, которые
    должны совпасть: "45 04 123456" и "4504 123456" (серия слитно).
    Используйте границы слова \\b с обеих сторон, чтобы не находить
    паспортный номер внутри более длинной цифровой последовательности.
    """

    INN_PATTERN: re.Pattern[str] = None  # type: ignore[assignment]
    """
    TODO: скомпилировать regex для ИНН — ЛИБО 12 подряд идущих цифр
    (физическое лицо), ЛИБО 10 подряд идущих цифр (юридическое лицо), с
    границами слова \\b с ОБЕИХ сторон у каждой альтернативы (а не
    просто \\d{10} без границ) — иначе выражение будет находить
    10-значную подстроку внутри 12-значного номера или внутри случайной
    длинной последовательности цифр (например, ОГРН), которая ИНН не
    является. Порядок альтернатив важен: сначала более длинный вариант
    (12 цифр), затем более короткий (10) — иначе более короткая
    альтернатива "перехватит" совпадение первой, и оставшиеся 2 цифры
    12-значного ИНН физлица не будут частью найденного совпадения.
    """

    MASK_TOKENS = {
        "email": "[EMAIL_REDACTED]",
        "phone": "[PHONE_REDACTED]",
        "snils": "[SNILS_REDACTED]",
        "passport": "[PASSPORT_REDACTED]",
        "inn": "[INN_REDACTED]",
    }
    """Маски по умолчанию для sanitize(mode="mask"). Типизированная
    маска (а не общий "[REDACTED]" без разбора) сохраняет полезность
    документа для чтения человеком — видно, что здесь БЫЛ номер
    телефона, а не что здесь случайно вырезан произвольный фрагмент."""

