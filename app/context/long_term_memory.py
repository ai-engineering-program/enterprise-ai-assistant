# Функция, возвращающая текущее время. Тот же принцип dependency injection,
# что и ClockFn у SessionMemory (5.1): без инъекции часов протестировать
# "факт трёхмесячной давности обновился новым значением" можно было бы
# только реальным ожиданием, что неприемлемо для unit-тестов.
ClockFn = Callable[[], datetime]


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


# Ключевые слова-сигналы того, что реплика, скорее всего, несёт устойчивый
# факт о клиенте (предпочтение, атрибут аккаунта), а не сиюминутную реплику
# разговора. Эвристика намеренно грубая и rule-based (тот же принцип, что и
# MessageQualityScorer, урок 1.2) — точная классификация "стоит ли запоминать
# факт навсегда" в production обычно требует отдельного вызова LLM с явным
# промптом извлечения; здесь — детерминированная заглушка для
# unit-тестирования логики хранения без единого реального вызова модели
# (см. текст урока, раздел "проблема извлечения").
DURABLE_FACT_KEYWORDS: tuple[str, ...] = (
    "тариф",
    "предпочита",
    "не звони",
    "удобн",
    "лицевой счёт",
    "адрес",
    "email",
    "почта",
)

# Короткие реплики-подтверждения — почти никогда не несут долговременного
# факта. Проверяются ДО ключевых слов и ТОЛЬКО как точное совпадение всей
# (обрезанной по краям) реплики — а не как подстрока, чтобы не отбрасывать
# длинные содержательные сообщения, случайно начинающиеся со слова "хорошо".
TRANSIENT_ACKNOWLEDGEMENT_PHRASES: tuple[str, ...] = (
    "спасибо",
    "хорошо",
    "понятно",
    "ок",
    "ладно",
    "угу",
)

# Реплики короче этого числа символов не рассматриваются как источник
# устойчивого факта — слишком мало содержания даже теоретически.
DEFAULT_MIN_WORTHY_LENGTH: int = 12


@dataclass
class Fact:
    """
    Одна версия факта о клиенте, извлечённая в долгосрочную память.

    Каждый remember_fact() создаёт НОВУЮ запись, а не перезаписывает
    предыдущую (append-with-timestamp, см. текст урока 5.2) — история
    изменений факта сохраняется целиком; какая из версий "актуальна",
    решает get_facts() в момент ЧТЕНИЯ, а не remember_fact() в момент
    записи. Полноценное разрешение конфликта нескольких версий одного
    факта — тема урока 5.4 (fact_key + journal pattern); здесь версии
    только накапливаются, не теряя данных.
    """

    user_id: str
    fact_key: str
    value: str
    recorded_at: datetime = field(default_factory=_utc_now)
    source_session_id: Optional[str] = None


